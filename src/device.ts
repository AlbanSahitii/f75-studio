import { invoke } from "@tauri-apps/api/core";
import previewSnapshot from "./preview.json";

/** Mirrors `KeyAction` in src-tauri/src/protocol.rs. */
export type KeyAction =
  | { kind: "none" }
  | { kind: "key"; modifiers: number; usage: number }
  | { kind: "mouse"; button: number; repeat: number; interval: number }
  | { kind: "media"; usage: number }
  | { kind: "macro"; mode: number; repeat: number; index: number }
  | { kind: "system"; code: number }
  | { kind: "lighting"; action: number; value: number }
  | { kind: "fn" }
  | { kind: "fn2" }
  | { kind: "other"; bytes: number[] };

export type Rgb = [number, number, number];
/** Mirrors `Step` in protocol.rs: a key's HID usage, a mouse button or a move; `up` = released; `delay` in ms. */
export type Step = { kind: "key" | "button" | "moveX" | "moveY" | "wheel"; up: boolean; code: number; delay: number };
export type Macro = { name: string; steps: Step[] };

export type Lighting = { effect: number; brightness: number; speed: number; colour: number };
export type Performance = { debounce: number; sleep: number };
/** `system`: 0 Windows, 1 Android, 2 Mac (Fn+W/Q/E). `knob`: 0 volume, 1 lighting (long press on the knob). */
export type Modes = { system: number; knob: number };
export type Battery = { level: number; charging: boolean };
export type Connection = "usb" | "wireless" | "none";
export type Status = { connection: Connection; battery: Battery | null };
export type Effect = { code: number; name: string; speed: boolean; brightness: boolean; colour: boolean };
/** App preferences (not keyboard settings), shared with the menu bar. */
export type Settings = { iso: boolean };

export type Snapshot = {
  lighting: Lighting;
  performance: Performance;
  modes: Modes;
  layers: KeyAction[][];
  effects: Effect[];
  sleepSteps: number[];
  /** Seven colours per effect, indexed by effect code; empty if the keyboard didn't give them. */
  palette: Rgb[][];
  /** The colours the palette's names ("Red", …) describe. */
  factoryPalette: Rgb[];
  /** Per-key colours (the Per-key effect), by key-matrix slot. */
  keyColours: Rgb[];
  macros: Macro[];
};

/** After a macro was recorded: the key's layer, and the macros now stored. */
export type MacroResult = { layer: KeyAction[]; macros: Macro[] };

export type Device = {
  status(): Promise<Status>;
  snapshot(): Promise<Snapshot>;
  /** Selects an effect; the keyboard keeps that effect's own brightness, speed and colour. */
  setEffect(effect: number): Promise<Lighting>;
  setLighting(lighting: Lighting): Promise<Lighting>;
  setPerformance(performance: Performance): Promise<Performance>;
  setModes(modes: Modes): Promise<Modes>;
  /** Opens System Settings at Input Monitoring. */
  openPrivacySettings(): Promise<void>;
  setKey(layer: number, index: number, action: KeyAction): Promise<KeyAction>;
  /** Paints keys for the Per-key effect; returns every key's colour. */
  setKeyColours(keys: number[], colour: Rgb): Promise<Rgb[]>;
  /** Changes one of an effect's seven colours; returns that effect's colours. */
  setPaletteColour(effect: number, slot: number, colour: Rgb): Promise<Rgb[]>;
  /** Records a macro onto a key. Other keys keep their macros. */
  setMacro(layer: number, index: number, macro: Macro): Promise<MacroResult>;
  restoreOriginal(): Promise<void>;
  settings(): Promise<Settings>;
  setLayout(iso: boolean): Promise<void>;
};

const tauri: Device = {
  status: () => invoke("status"),
  snapshot: () => invoke("snapshot"),
  setEffect: (effect) => invoke("set_effect", { effect }),
  setLighting: (lighting) => invoke("set_lighting", { lighting }),
  setPerformance: (performance) => invoke("set_performance", { performance }),
  setModes: (modes) => invoke("set_modes", { modes }),
  openPrivacySettings: () => invoke("open_privacy_settings"),
  setKey: (layer, index, action) => invoke("set_key", { layer, index, action }),
  setKeyColours: (keys, colour) => invoke("set_key_colours", { keys, colour }),
  setPaletteColour: (effect, slot, colour) => invoke("set_palette_colour", { effect, slot, colour }),
  setMacro: (layer, index, macro) => invoke("set_macro", { layer, index, recorded: macro }),
  restoreOriginal: () => invoke("restore_original"),
  settings: () => invoke("settings"),
  setLayout: (iso) => invoke("set_layout", { iso }),
};

/**
 * Browser preview (`npm run dev` outside Tauri): an in-memory keyboard seeded from real fixtures,
 * regenerated by `cargo test -- --ignored preview`. `?connection=none|wireless` previews the empty states.
 */
function preview(): Device {
  const original = previewSnapshot as unknown as Snapshot;
  let snap: Snapshot = structuredClone(original);
  let prefs: Settings = { iso: false };
  const connection = (new URLSearchParams(location.search).get("connection") ?? "usb") as Connection;
  const later = <T>(value: T) => new Promise<T>((resolve) => setTimeout(() => resolve(structuredClone(value)), 120));
  return {
    status: () => later({ connection, battery: connection === "usb" ? { level: 72, charging: false } : null }),
    snapshot: () => later(snap),
    setEffect: (effect) => later((snap.lighting = { ...snap.lighting, effect })),
    setLighting: (lighting) => later((snap.lighting = lighting)),
    setPerformance: (performance) => later((snap.performance = performance)),
    setModes: (modes) => later((snap.modes = modes)),
    openPrivacySettings: () => later(undefined),
    setKey: (layer, index, action) => later((snap.layers[layer][index] = action)),
    setKeyColours: (keys, colour) => later((keys.forEach((k) => (snap.keyColours[k] = colour)), snap.keyColours)),
    setPaletteColour: (effect, slot, colour) => later(((snap.palette[effect][slot] = colour), snap.palette[effect])),
    setMacro: (layer, index, macro) => {
      snap.macros.push(macro);
      snap.layers[layer][index] = { kind: "macro", mode: 1, repeat: 1, index: snap.macros.length - 1 };
      return later({ layer: snap.layers[layer], macros: snap.macros });
    },
    restoreOriginal: () => later(void (snap = structuredClone(original))),
    settings: () => later(prefs),
    setLayout: (iso) => later(void (prefs = { iso })),
  };
}

/** A stock F75 default layer (captured from a real keyboard), to draw the board before one is connected. */
export const factoryLayer = (previewSnapshot as unknown as Snapshot).layers[0];

export const isPreview = !("__TAURI_INTERNALS__" in window);
export const device: Device = isPreview ? preview() : tauri;
